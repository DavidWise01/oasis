check('schema v8.1',()=>assert.equal(s.schema,'oasis/n184/arc-phase-time/v81'));
check('literal user phase time rule',()=>assert.equal(s.userRuleLiteral,'phase time is n x 1.25%'));
check('step exactly 1.25 percent',()=>assert.equal(s.phaseTime.stepPercent,1.25));
check('step exactly 0.0125',()=>assert.equal(s.phaseTime.stepFraction,.0125));
check('step reduced rational one over eighty',()=>assert.deepEqual(s.phaseTime.stepRational,{numerator:1,denominator:80}));
check('index starts at zero',()=>assert.equal(s.phaseTime.domain.nMin,0));
check('index ends at eighty',()=>assert.equal(s.phaseTime.domain.nMax,80));
check('integer indexes',()=>assert.equal(s.phaseTime.domain.nInteger,true));
check('eighty steps exactly',()=>assert.equal(s.phaseTime.stepsPerCycle,80));
check('eighty steps return 100 percent',()=>assert.equal(s.phaseTime.stepsPerCycle*s.phaseTime.stepPercent,s.phaseTime.fullCyclePercent));
check('step 0 initial 0 percent',()=>assert.equal(0*s.phaseTime.stepPercent,0));
check('step 1 1.25 percent',()=>assert.equal(1*s.phaseTime.stepPercent,1.25));
check('step 20 25 percent',()=>assert.equal(20*s.phaseTime.stepPercent,25));
check('step 40 50 percent',()=>assert.equal(40*s.phaseTime.stepPercent,50));
check('step 60 75 percent',()=>assert.equal(60*s.phaseTime.stepPercent,75));
check('step 80 100 percent',()=>assert.equal(80*s.phaseTime.stepPercent,100));
check('one step 4.5 degrees',()=>assert.equal(s.angleMapping.degreesPerStep,4.5));
check('eighty increments are 360 degrees',()=>assert.equal(80*s.angleMapping.degreesPerStep,360));
check('full cycle matches parent 360 degrees',()=>assert.equal(s.angleMapping.cycleDegrees,v80.nominal.phaseCycleDegrees));
