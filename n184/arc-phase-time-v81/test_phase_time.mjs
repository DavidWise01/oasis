check('end and wrap explicitly separated',()=>assert.ok(s.phaseTime.normalizedEndConvention.includes('n=80')));
check('shared XYZ kept',()=>assert.deepEqual(s.inherited.sharedAxes,{x:'state',y:'space',z:'state+time'}));
check('nine Sag A clones kept',()=>assert.equal(s.inherited.sagAUniverseInstances,9));
check('Earth remains M',()=>assert.ok(s.inherited.M.includes('Earth')));
check('view displays 1.25 percent and source link',()=>{const h=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');assert.ok(h.includes('1.25%'));assert.ok(h.includes('../arc-cycle-v80/spec.json'))});
console.log(JSON.stringify({result:'PASS',passed:Object.keys(results).length,failed:0,checks:results},null,2));
