check('calibrated length per step',()=>assert.equal(s.lengthMapping.calibratedPerStepMeters,s.lengthMapping.calibratedFullCycleMeters/80));
check('n80 restores nominal bubble length',()=>assert.equal(s.lengthMapping.nominalFullCycleMeters*80/80,v80.nominal.userLengthMeters));
check('Planck length source unmodified',()=>assert.equal(s.inherited.planckLengthMeters,v78.scales[2].length.value));
check('Planck time source unmodified',()=>assert.equal(s.inherited.planckTimeSeconds,v78.scales[2].time.value));
check('Planck time is not default cycle duration',()=>assert.equal(s.inherited.planckTimeDoesNotAutomaticallySetCycleSeconds,true));
check('reference duration in seconds unassigned',()=>assert.equal(s.phaseTime.referenceDurationSeconds,null));
check('elapsed absolute seconds unassigned',()=>assert.equal(s.phaseTime.elapsedSeconds,null));
