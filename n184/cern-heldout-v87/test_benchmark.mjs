import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseCMSCSV} from '../cern-observer-lab-v84/observer_core.mjs';
import {DATA_URL,DATA_DOI,fnv1a32,isHeldOut,predictMass,evaluate,runCsv} from './benchmark.mjs';
const txt=fs.readFileSync(new URL('../cern-observer-lab-v84/sample-cms-education.csv',import.meta.url),'utf8');
const rs=parseCMSCSV(txt).records, result=evaluate(rs);
const spec=JSON.parse(fs.readFileSync(new URL('./spec.json',import.meta.url),'utf8'));
const checks={};const test=(name,cb)=>{cb();checks[name]=true};
const near=(a,b,e=1e-12)=>assert.ok(Math.abs(a-b)<=e,String(a)+' not within '+String(e)+' of '+String(b));
test('schema v87',()=>assert.equal(spec.schema,'oasis/n184/cern-heldout/v87'));
test('100k events target',()=>assert.ok(spec.target.includes('100000')));
test('CERN open DOI preserved',()=>assert.equal(DATA_DOI,'10.7483/OPENDATA.CMS.CB8H.MFFA'));
test('CERN ROOT official source URL',()=>assert.ok(DATA_URL.startsWith('https://root.cern.ch/')));
test('FNV empty input offset',()=>assert.equal(fnv1a32(''),0x811c9dc5));
test('FNV deterministic',()=>assert.equal(fnv1a32('abc'),fnv1a32('abc')));
test('FNV input sensitive',()=>assert.notEqual(fnv1a32('abc'),fnv1a32('abd')));
test('FNV known vector',()=>assert.equal(fnv1a32('hello'),0x4f9f2cab));
test('first sample reserved',()=>assert.equal(isHeldOut(rs[0]),false));
test('last sample held out',()=>assert.equal(isHeldOut(rs[3]),true));
test('sample 4 records',()=>assert.equal(rs.length,4));
test('all model predictions finite on sample',()=>assert.ok(rs.every(r=>['transverse','angular','fourPort','fourVector'].every(m=>Number.isFinite(predictMass(r,m))))));
test('target mass never in prediction: transverse',()=>{const r={...rs[0],M:99999};assert.equal(predictMass(r,'transverse'),predictMass(rs[0],'transverse'))});
test('target mass never in prediction: angular',()=>{const r={...rs[0],M:99999};assert.equal(predictMass(r,'angular'),predictMass(rs[0],'angular'))});
test('target mass never in prediction: fourVector',()=>{const r={...rs[0],M:99999};assert.equal(predictMass(r,'fourVector'),predictMass(rs[0],'fourVector'))});
test('angular matches fourPort by design',()=>rs.forEach(r=>assert.equal(predictMass(r,'angular'),predictMass(r,'fourPort'))));
test('angular is not generally equal to transverse',()=>assert.ok(rs.some(r=>predictMass(r,'angular')>predictMass(r,'transverse'))));
test('changing eta affects angular output',()=>{const r={...rs[0],eta2:rs[0].eta1};assert.notEqual(predictMass(r,'angular'),predictMass(rs[0],'angular'))});
test('changing eta does not affect transverse',()=>{const r={...rs[0],eta2:99};assert.equal(predictMass(r,'transverse'),predictMass(rs[0],'transverse'))});
test('changing charge does not alter angular mass',()=>{const r={...rs[0],Q1:-rs[0].Q1};assert.equal(predictMass(r,'angular'),predictMass(rs[0],'angular'))});
test('unknown mode rejected',()=>assert.throws(()=>predictMass(rs[0],'nonexistent')));
test('massless analytic transverse positive',()=>assert.ok(predictMass(rs[0],'transverse')>=0));
test('zero eta difference angular equals transverse',()=>{const r={...rs[0],eta2:rs[0].eta1};near(predictMass(r,'angular'),predictMass(r,'transverse'),1e-10)});
test('same p, energies gives physical fourvector',()=>{const r={E1:5,E2:5,px1:0,px2:0,py1:0,py2:0,pz1:0,pz2:0};assert.equal(predictMass(r,'fourVector'),10)});
test('unphysical fourvector returns NaN',()=>{const r={E1:0,E2:0,px1:10,px2:0,py1:0,py2:0,pz1:0,pz2:0};assert.ok(Number.isNaN(predictMass(r,'fourVector')))});
test('holdout from known sample one',()=>assert.equal(result.heldOutCount,1));
test('reserved from known sample three',()=>assert.equal(result.reservedCount,3));
test('holdout id independent of M value',()=>assert.equal(isHeldOut({...rs[0],M:0}),isHeldOut(rs[0])));
test('each metric one observation',()=>Object.values(result.metrics).forEach(v=>assert.equal(v.n,1)));
test('four-port and angular mean errors equal',()=>assert.equal(result.metrics.fourPort.maeGeV,result.metrics.angular.maeGeV));
test('four-port gain zero',()=>assert.equal(result.comparisons.fourPortVsAngularMAEGeV,0));
test('3D four-vector residual small',()=>assert.ok(result.metrics.fourVector.maeGeV<.001));
test('massless angular improves on transverse in sample holdout',()=>assert.ok(result.metrics.angular.maeGeV<result.metrics.transverse.maeGeV));
test('full record counts',()=>assert.equal(result.rowsProcessed,4));
test('holdout sample record provenance',()=>assert.equal(result.sampleOfHoldout[0].event,90678594));
test('empty dataset metrics null',()=>assert.equal(evaluate([]).metrics.transverse.maeGeV,null));
test('maxRows constrained to 100k',()=>assert.throws(()=>evaluate(rs,{maxRows:100001})));
test('invalid input throws',()=>assert.throws(()=>evaluate('not an array')));
test('runCsv wrapper sample four',()=>assert.equal(runCsv(txt).input.accepted,4));
test('parser reject wrong row',()=>assert.equal(runCsv(txt.replace('19.1712','NaN')).input.skipped,1));
test('CERN symbolic carbon six conserved',()=>assert.equal(spec.preserved.carbonAtomicNumber,6));
test('240 ring and 80 phase conserved',()=>assert.deepEqual([spec.preserved.microticks,spec.preserved.phaseSteps],[240,80]));
test('Gen0 Ada preserved',()=>assert.equal(spec.preserved.gen0,1832));
test('Gen1 1970 preserved',()=>assert.equal(spec.preserved.gen1,1970));
test('historical nature offset zero',()=>assert.equal(spec.preserved.natureOffset,0));
test('dataset educational-only disclaimer',()=>assert.ok(spec.guardrails.some(t=>t.includes('Education/outreach'))));
test('reference label leakage formally barred',()=>assert.ok(spec.split.leakageRule.includes('M is read only')));
test('no old files overwritten',()=>assert.ok(fs.existsSync(new URL('../carbon-3d-cern-v86/spec.json',import.meta.url))));
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0,
 sample:{records:rs.length,holdout:result.heldOutCount,metrics:result.metrics},
 checks},null,2));
