import assert from 'node:assert/strict';
import fs from 'node:fs';
const load=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const s=load('./spec.json'),v76=load('../scale-xyz-v76/spec.json'),clock=load('../time-stack-tmb-v74/spec.json');
const checks={};const check=(k,f)=>{f();checks[k]=true};
check('schema v7.7',()=>assert.equal(s.schema,'oasis/n184/scale-xyz/v77'));
check('raw notation not lost',()=>assert.equal(s.userLiteral,'13.8byears = 1 year = 1x1.6161^10-35seconds'));
check('scale not physical equality',()=>assert.ok(s.equalitySemantics.includes('not equality')));
check('interpretation documented',()=>assert.ok(s.parseAssumption.includes('scientific notation')));
check('X state preserved',()=>assert.equal(s.grammar.x,v76.axes[0].userLabel));
check('Y space preserved',()=>assert.equal(s.grammar.y,v76.axes[1].userLabel));
check('Z state plus time preserved',()=>assert.equal(s.grammar.z,v76.axes[2].userLabel));
check('three anchors T M B',()=>assert.deepEqual(s.anchors.map(x=>x.code),['T','M','B']));
check('star planet atom preserved',()=>assert.deepEqual(s.anchors.map(x=>x.analogy),['star','planet','atom']));
check('plank names preserved',()=>assert.deepEqual(s.anchors.map(x=>x.symbolic),['plank bubble','plank foam','plank']));
check('upper cosmic 13.8 billion Julian years',()=>assert.equal(s.anchors[0].seconds,13.8e9*31557600));
check('middle Earth one Julian year',()=>{assert.equal(s.anchors[1].seconds,31557600);assert.equal(s.anchors[1].reference,'Earth')});
check('bottom user value in seconds',()=>assert.equal(s.anchors[2].seconds,1.6161e-35));
check('strict time scale ordering',()=>assert.ok(s.anchors[0].seconds>s.anchors[1].seconds&&s.anchors[1].seconds>s.anchors[2].seconds));
check('unequal ratios so not uniform scaling',()=>assert.notEqual(s.transitions[0].ratio,s.transitions[1].ratio));
check('first ratio exactly 13.8 billion',()=>assert.equal(s.transitions[0].ratio,13.8e9));
check('second ratio seconds normalized',()=>assert.equal(s.transitions[1].ratio,s.anchors[1].seconds/s.anchors[2].seconds));
check('legacy operator preserved',()=>assert.equal(s.priorClock.literal,clock.clock.literal));
check('legacy clock not retroactively changed',()=>assert.equal(s.priorClock.secondsPerTick,clock.clock.secondsPerTick));
check('legacy 13/8B unresolved',()=>assert.equal(s.priorClock.status.includes('undefined'),true));
check('not Planck time: official coefficient and exponent',()=>{assert.equal(s.units.standardPlanckTimeSeconds,5.391247e-44);assert.ok(s.units.standardPlanckTimeSeconds!==s.anchors[2].seconds)});
check('Planck length units remain meters',()=>assert.ok(s.units.standardPlanckLengthMeters===1.616255e-35));
check('no unsupported physical equivalence',()=>assert.ok(s.scientificBoundary.some(x=>x.includes('not represent equal elapsed time'))));
check('9 original symbolic universes preserved',()=>assert.equal(s.retainedTopology.identicalSymbolicSagAUniverses,9));
check('Earth is the middle',()=>assert.equal(s.retainedTopology.middle,'Earth reference'));
check('page contains original notation',()=>assert.ok(fs.readFileSync(new URL('./index.html',import.meta.url),'utf8').includes(s.userLiteral)));
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0,checks},null,2));
