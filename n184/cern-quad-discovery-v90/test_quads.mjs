import fs from 'node:fs';
import assert from 'node:assert/strict';
const spec=JSON.parse(fs.readFileSync(new URL('./spec.json',import.meta.url),'utf8'));
const q=spec.quadruple;
const checks={};function check(name,fn){fn();checks[name]=true}
const by=n=>q.find(e=>e.quad===n);
check('v90 schema',()=>assert.equal(spec.schema,'oasis/n184/cern-quad-discovery/v90'));
check('four distinct names',()=>assert.deepEqual(q.map(e=>e.quad),['A','B','C','D']));
check('ALICE A',()=>assert.equal(by('A').experiment,'ALICE'));
check('ATLAS B',()=>assert.equal(by('B').experiment,'ATLAS'));
check('CMS C',()=>assert.equal(by('C').experiment,'CMS'));
check('LHCb D',()=>assert.equal(by('D').experiment,'LHCb'));
check('IP2 ALICE',()=>assert.equal(by('A').ip,2));
check('IP1 ATLAS',()=>assert.equal(by('B').ip,1));
check('IP5 CMS',()=>assert.equal(by('C').ip,5));
check('IP8 LHCb',()=>assert.equal(by('D').ip,8));
check('two beam paths one accelerator ring',()=>assert.deepEqual([spec.realLayout.acceleratorRingsInSite,spec.realLayout.counterCirculatingBeamPaths],[1,2]));
check('8 interaction points',()=>assert.equal(spec.realLayout.acceleratorInteractionPoints,8));
check('4 major detector points',()=>assert.equal(spec.realLayout.selectedMajorExperimentPoints,4));
check('4 concept quads not physical sectors',()=>assert.equal(spec.realLayout.modelLogicalQuadCount,4));
check('LHC technical sector count 8',()=>assert.equal(spec.realLayout.physicalSectorCount,8));
check('ALICE zero toroids',()=>assert.equal(by('A').physicalToroidSystems,0));
check('ATLAS three toroids',()=>assert.equal(by('B').physicalToroidSystems,3));
check('CMS zero toroids',()=>assert.equal(by('C').physicalToroidSystems,0));
check('LHCb zero toroids',()=>assert.equal(by('D').physicalToroidSystems,0));
check('total toroids 3',()=>assert.equal(q.reduce((n,e)=>n+e.physicalToroidSystems,0),3));
check('total toroid coils 24',()=>assert.equal(q.reduce((n,e)=>n+e.physicalToroidCoils,0),24));
check('barrel 1 and two end caps',()=>assert.deepEqual(by('B').toroidBreakdown.map(x=>x.count),[1,2]));
check('eight superconducting coils each toroid',()=>assert.ok(by('B').toroidBreakdown.every(x=>x.coilsPerMagnet===8)));
check('coil count arithmetic matches 24',()=>assert.equal(by('B').toroidBreakdown.reduce((s,x)=>s+x.coilsPerMagnet*x.count,0),24));
check('ATLAS also uses solenoid',()=>assert.ok(by('B').otherMagnets.includes('central solenoid')));
check('ALICE uses dipole',()=>assert.ok(by('A').magnets.some(x=>x.includes('dipole'))));
check('CMS solenoid',()=>assert.ok(by('C').magnets.some(x=>x.includes('solenoid'))));
check('LHCb spectrometer dipole',()=>assert.ok(by('D').magnets.some(x=>x.includes('dipole'))));
check('one Higgs species joint discovery 2012',()=>{
 const a=by('B').discoveries.find(x=>x.name==='Higgs boson'),c=by('C').discoveries.find(x=>x.name==='Higgs boson');
 assert.equal(a.year,2012);assert.equal(c.year,2012);
 assert.ok(a.status.startsWith('joint'));assert.ok(c.status.startsWith('joint'))
});
check('CMS Xi_b star identified',()=>assert.ok(by('C').discoveries.some(x=>x.name==='Xi_b*0 baryon'&&x.year===2012)));
check('ATLAS Bc star 2026',()=>assert.ok(by('B').discoveries.some(x=>x.name==='B_c*+ meson'&&x.year===2026)));
check('ALICE anti hyperhelium evidence not discovery',()=>assert.ok(by('A').discoveries.some(x=>x.name==='Antihyperhelium-4'&&x.status.includes('3.5 sigma'))));
check('ALICE QGP state not a particle',()=>assert.ok(by('A').discoveries.some(x=>x.name==='Quark–gluon plasma'&&x.type.includes('state'))));
check('LHCb pentaquarks 2015',()=>assert.ok(by('D').discoveries.some(x=>x.name.includes('Pentaquark')&&x.year===2015)));
check('LHCb Xi cc 2017',()=>assert.ok(by('D').discoveries.some(x=>x.name==='Xi_cc++ baryon'&&x.year===2017)));
check('LHCb 2026 doubly charmed ccs',()=>assert.ok(by('D').discoveries.some(x=>x.name.includes('Omega_cc+')&&x.year===2026)));
check('all examples have external verified source URLs',()=>assert.ok(q.every(x=>x.discoveries.every(d=>d.source.startsWith('https://')))));
check('not an exhaustive particle count',()=>assert.ok(spec.claimLimits.some(x=>x.includes('not an exhaustive'))));
check('toroid meaning is magnet systems not ring',()=>assert.ok(spec.toroidCountMeaning.includes('not individual coils')));
check('equal physical quadrant interpretation ruled out',()=>assert.ok(spec.quadInterpretation.includes('not four equal-length')));
check('legacy carbon layer unchanged',()=>assert.equal(spec.userSymbolicOverlay.carbonLayer,3));
check('legacy 6 arcs unchanged',()=>assert.equal(spec.userSymbolicOverlay.outerArcs,6));
check('legacy 80 phases unchanged',()=>assert.equal(spec.userSymbolicOverlay.phaseSteps,80));
check('legacy 240 microticks unchanged',()=>assert.equal(spec.userSymbolicOverlay.microticks,240));
check('Ada gen0 1832',()=>assert.equal(spec.userSymbolicOverlay.historicalGen0,1832));
check('Toroidal gen1 1970',()=>assert.equal(spec.userSymbolicOverlay.historicalGen1,1970));
check('Nature offset symbolic 0',()=>assert.equal(spec.userSymbolicOverlay.motherNatureOffsetYears,0));
check('interactive dual-view page wired',()=>{
 const h=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
 for(const t of ["'physical'","'logical'","./spec.json","discoveries","physicalToroidSystems"])assert.ok(h.includes(t));
});
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0},null,2));
