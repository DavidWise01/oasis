import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const s=read('./spec.json'),old=read('../time-stack-tmb-v75/spec.json'),clock=read('../time-stack-tmb-v74/spec.json'),web=read('../jellyfish-web-v73/spec.json');
const checks={};function check(name,fn){fn();checks[name]=true}
check('v7.6 schema',()=>assert.equal(s.schema,'oasis/n184/scale-xyz/v76'));
check('three axes only',()=>assert.deepEqual(s.axes.map(x=>x.name),['x','y','z']));
check('x literal state',()=>assert.equal(s.axes[0].userLabel,'state'));
check('y literal space',()=>assert.equal(s.axes[1].userLabel,'space'));
check('z literal state+time',()=>assert.equal(s.axes[2].userLabel,'state+time'));
check('z pair semantics',()=>assert.deepEqual(s.axes[2].serialization,['state','time']));
check('no cross-unit arithmetic claimed',()=>assert.equal(s.axes[2].arithmeticAddition,false));
check('single grammar across scales',()=>assert.equal(s.invariants.acrossScales,'same x/y/z grammar'));
check('T/M/B preserved',()=>assert.deepEqual(s.scales.map(x=>x.code),['T','M','B']));
check('star/planet/atom aliases preserved',()=>assert.deepEqual(s.scales.map(x=>x.analogy),['star','planet','atom']));
check('plank vocabulary preserved',()=>assert.deepEqual(s.scales.map(x=>x.symbolic),['plank bubble','plank foam','plank']));
check('T/M/B legacy terms preserved',()=>assert.deepEqual(s.scales.map(x=>x.legacy),['strong','medium','floor']));
check('M Earth reference preserved',()=>assert.equal(s.scales[1].reference,'Earth'));
check('five upper and four lower clones',()=>assert.deepEqual(s.scales.map(x=>x.cloneCount),[5,0,4]));
check('earth no universe increment',()=>assert.equal(s.invariants.earthAddsUniverse,false));
check('nine original Sag A nodes',()=>assert.equal(web.nodes.length,s.invariants.clonedSagAUniverseCount));
check('clock literal unchanged',()=>assert.equal(s.invariants.timeNotation,clock.clock.literal));
check('model tick unchanged',()=>assert.equal(s.invariants.secondsPerSymbolicTick,clock.clock.secondsPerTick));
check('symbolic operator not evaluated',()=>{assert.equal(s.invariants.clockOperator,'13/8B');assert.equal(s.invariants.clockOperatorDefined,false)});
check('no unsupported numeric scale claim',()=>assert.ok(s.invariants.scaleFactors.includes('unspecified')));
check('v75 aliases match v76',()=>assert.deepEqual(s.scales.map(x=>x.analogy),old.bands.map(x=>x.analogy)));
check('orbital evidence path unchanged',()=>assert.equal(s.sourcePaths.evidence,old.inherits.evidence));
check('root anchor 1 unchanged',()=>assert.equal(s.invariants.rootAnchor,1));
check('view displays literal axis spelling',()=>{const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');for(const token of ['state+time','X · state','Y · space','Z · state + time'])assert.ok(html.includes(token),token)});
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0,checks},null,2));
