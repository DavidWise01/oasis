import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const s=read('./spec.json'),p=read('../scale-xyz-v78/spec.json'),c=read('../scale-xyz-v76/spec.json');
const B=p.scales.find(x=>x.code==='B'),checks={};
const check=(name,fn)=>{fn();checks[name]=true};
check('schema v7.9',()=>assert.equal(s.schema,'oasis/n184/arc-bubble/v79'));
check('source v7.8',()=>assert.equal(s.source.planckRegister,'../scale-xyz-v78/spec.json'));
check('user original statement',()=>assert.equal(s.userRuleLiteral,'one arc bubble is 1/6 plank length'));
check('user spelling retained',()=>assert.equal(s.spelling.userTerm,'plank'));
check('scientific name separate',()=>assert.equal(s.spelling.scientificTerm,'Planck'));
check('Planck basis length',()=>assert.equal(s.basis.valueMeters,B.length.value));
check('arc numerator one',()=>assert.equal(s.arcBubble.partNumerator,1));
check('arc denominator six',()=>assert.equal(s.arcBubble.partDenominator,6));
check('literal fraction 1/6',()=>assert.equal(s.arcBubble.fractionString,'1/6'));
check('one arc length exact',()=>assert.equal(s.arcBubble.arcLengthMeters,B.length.value/6));
check('six arcs sum to Planck length',()=>assert.equal(s.arcBubble.arcLengthMeters*6,s.basis.valueMeters));
check('segment count six',()=>assert.equal(s.arcBubble.segmentsPerCompleteLength,6));
check('arc dimension length',()=>assert.equal(s.arcBubble.dimension,'length'));
check('arc in meters',()=>assert.equal(s.basis.dimension,'length'));
check('time independently preserved',()=>assert.equal(s.planckTime.valueSeconds,B.time.value));
check('Planck time seconds',()=>assert.equal(s.planckTime.unit,'second'));
check('no arc duration assigned',()=>assert.equal(s.planckTime.noInherentArcDuration,true));
check('loop is optional visualization',()=>assert.equal(s.illustrativeRing.chosenRepresentation.includes('diagram convention'),true));
check('six 60-degree arcs',()=>assert.equal(s.illustrativeRing.angleDegreesPerArc*6,360));
check('ring closure preserves circumference conditionally',()=>assert.equal(s.illustrativeRing.totalArcLengthMeters,s.basis.valueMeters));
check('conditional radius formula',()=>assert.equal(s.illustrativeRing.conditionalRadiusMeters,s.basis.valueMeters/(2*Math.PI)));
check('conditional chord not arc length',()=>assert.ok(s.illustrativeRing.conditionalChordMeters<s.arcBubble.arcLengthMeters));
check('shared XYZ grammar retained',()=>assert.deepEqual([s.sharedAxes.x,s.sharedAxes.y,s.sharedAxes.z],c.axes.map(x=>x.userLabel)));
check('Earth middle',()=>assert.equal(s.inherited.earthReference,'M'));
check('prior Sag A nine copies',()=>assert.equal(s.inherited.sagAUniverseCopies,9));
check('legacy symbolic time kept',()=>assert.equal(s.inherited.legacyTimeLiteral,p.model.earlierSymbolicClock));
check('CODATA link preserved',()=>assert.equal(s.basis.reference,p.constants.url));
check('no false hard indivisible Planck premise',()=>assert.ok(s.classification.some(x=>x.includes('not experimentally established'))));
check('HTML loads canonical data',()=>{const h=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');assert.ok(h.includes('./spec.json'));assert.ok(h.includes('../scale-xyz-v78/spec.json'))});
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0,checks},null,2));
