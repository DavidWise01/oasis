import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseCMSCSV} from '../cern-observer-lab-v84/observer_core.mjs';
import {isHeldOut} from '../cern-heldout-v87/benchmark.mjs';
import {CASES,SOURCE_SHA256,caseFor,mass4,injectFault,estimatePz,witness,naiveMass,evaluate,runCSV} from './recovery.mjs';

const spec=JSON.parse(fs.readFileSync(new URL('./spec.json',import.meta.url),'utf8'));
const text=fs.readFileSync(new URL('../cern-observer-lab-v84/sample-cms-education.csv',import.meta.url),'utf8');
const events=parseCMSCSV(text).records, r=events[0];
const checks={};const test=(name,fn)=>{fn();checks[name]=true};
const near=(a,b,tol=1e-9)=>assert.ok(Number.isFinite(a)&&Math.abs(a-b)<=tol,String(a)+' versus '+String(b));

test('v88 schema',()=>assert.equal(spec.schema,'oasis/n184/cern-fault-recovery/v88'));
test('same registered CERN source hash',()=>assert.equal(spec.data.referenceSha256,SOURCE_SHA256));
test('three synthetic case names',()=>assert.deepEqual(CASES,['clean','missing_pz1','biased_pz1_plus5']));
test('case for deterministic',()=>assert.equal(caseFor(r),caseFor(r)));
test('case selected from declared set',()=>assert.ok(CASES.includes(caseFor(r))));
test('all cases possible from synthetic event identifiers',()=>{
 const sample=Array.from({length:300},(_,i)=>caseFor({...r,Event:10000+i}));
 assert.equal(new Set(sample).size,3)
});
test('complete pz reconstructed full-mass finite',()=>assert.ok(Number.isFinite(mass4(r))));
test('mass formula reproduces sample to tolerance',()=>near(mass4(r),r.M,.001));
test('missing pz1 is nonfinite for strict mass',()=>assert.ok(Number.isNaN(mass4({...r,pz1:null}))));
test('unphysical fourvector rejected',()=>assert.ok(Number.isNaN(mass4({...r,E1:0,E2:0,px1:2000}))));
test('clean injection leaves original value',()=>assert.equal(injectFault(r,'clean').pz1,r.pz1));
test('clean injection makes a copy',()=>assert.notEqual(injectFault(r,'clean'),r));
test('missing fault sets explicit null',()=>assert.equal(injectFault(r,'missing_pz1').pz1,null));
test('bias injection adds 5 GeV',()=>assert.equal(injectFault(r,'biased_pz1_plus5').pz1,r.pz1+5));
test('injected failure does not mutate source',()=>{const p=r.pz1;injectFault(r,'missing_pz1');assert.equal(r.pz1,p)});
test('unknown fault rejected',()=>assert.throws(()=>injectFault(r,'rogue')));
test('pt sinh eta finite on CERN example',()=>assert.ok(Number.isFinite(estimatePz(r))));
test('pt sinh eta approximately reproduces pz1',()=>near(estimatePz(r),r.pz1,.05));
test('invalid eta makes estimate invalid',()=>assert.ok(Number.isNaN(estimatePz({...r,eta1:NaN}))));
test('invalid pt makes estimate invalid',()=>assert.ok(Number.isNaN(estimatePz({...r,pt1:-3}))));
test('missing pz triggers witness alarm',()=>assert.equal(witness(injectFault(r,'missing_pz1')).alarm,true));
test('missing pz repaired',()=>assert.equal(witness(injectFault(r,'missing_pz1')).canRepair,true));
test('recovered pz equals independent-column formula',()=>near(witness(injectFault(r,'missing_pz1')).repaired.pz1,estimatePz(r)));
test('drift triggers witness alarm',()=>assert.equal(witness(injectFault(r,'biased_pz1_plus5')).alarm,true));
test('drift repair replaces biased pz',()=>near(witness(injectFault(r,'biased_pz1_plus5')).repaired.pz1,estimatePz(r)));
test('clean unchanged',()=>assert.equal(witness(r).modified,false));
test('clean no alarm',()=>assert.equal(witness(r).alarm,false));
test('missing with invalid eta cannot be repaired',()=>assert.equal(witness({...r,pz1:null,eta1:NaN}).canRepair,false));
test('small pz perturbation beneath threshold not falsely flagged',()=>assert.equal(witness({...r,pz1:estimatePz(r)+.01}).alarm,false));
test('naive missing baseline fills zero',()=>near(naiveMass({...r,pz1:null}),mass4({...r,pz1:0}),1e-10));
test('naive drift trusts corrupted pz',()=>near(naiveMass(injectFault(r,'biased_pz1_plus5')),mass4(injectFault(r,'biased_pz1_plus5')),1e-10));
test('recovery mass of missing sample near clean mass',()=>near(mass4(witness(injectFault(r,'missing_pz1')).repaired),mass4(r),.05));
test('recovery mass drift sample near clean mass',()=>near(mass4(witness(injectFault(r,'biased_pz1_plus5')).repaired),mass4(r),.05));
test('holdout rule reused',()=>assert.equal(events.filter(isHeldOut).length,1));
test('fixture eval heldout one event',()=>assert.equal(evaluate(events).heldout,1));
test('fixture eval reserved 3',()=>assert.equal(evaluate(events).reserved,3));
test('scenario totals match holdout',()=>{const x=evaluate(events);assert.equal(Object.values(x.scenarios).reduce((s,t)=>s+t.n,0),x.heldout)});
test('example count ≤ 18',()=>assert.ok(evaluate(events).examples.length<=18));
test('mass reconstruction finite when r M changed',()=>{const fake={...r,M:99999};assert.equal(witness(fake).repaired.pz1,witness(r).repaired.pz1)});
test('detector input does not read M',()=>assert.equal(witness({...r,M:0}).alarm,witness(r).alarm));
test('known 80-step model invariant',()=>assert.equal(spec.invariants.phaseSteps,80));
test('known 6-sector model invariant',()=>assert.equal(spec.invariants.sectors,6));
test('known 240-microtick invariant',()=>assert.equal(spec.invariants.microticks,240));
test('carbon layer 3D',()=>assert.equal(spec.invariants.carbonLayer,3));
test('Gen0 1832',()=>assert.equal(spec.invariants.gen0,1832));
test('Gen1 1970',()=>assert.equal(spec.invariants.gen1,1970));
test('nature offset zero',()=>assert.equal(spec.invariants.motherNatureOffset,0));
test('CERN collision provenance explicit',()=>assert.ok(spec.data.source.includes('root.cern.ch')));
test('test distinguishes synthetic faults from real detector faults',()=>assert.ok(spec.limits.some(x=>x.includes('not cross-detector'))));
test('CSV wrapper consistent holdout',()=>assert.equal(runCSV(text).analysis.heldout,1));
test('invalid maxRows fails',()=>assert.throws(()=>evaluate(events,{maxRows:100001})));
test('invalid event list fails',()=>assert.throws(()=>evaluate('not an array')));
test('baseline old 100k results intact',()=>assert.ok(fs.existsSync(new URL('../cern-heldout-v87/results.json',import.meta.url))));
const saved=JSON.parse(fs.readFileSync(new URL('./results.json',import.meta.url),'utf8'));
test('saved 100k CERN source accepted',()=>assert.equal(saved.input.accepted,100000));
test('saved holdout exactly 19993',()=>assert.equal(saved.analysis.heldout,19993));
test('saved source SHA256 preserved',()=>assert.equal(saved.provenance.sourceSha256,SOURCE_SHA256));
test('saved experiment reports zero clean false alarms',()=>assert.equal(saved.analysis.scenarios.clean.falseAlarms,0));
test('saved one missed injected bias',()=>assert.equal(saved.analysis.scenarios.biased_pz1_plus5.missedFaults,1));
test('saved recovered coverage 19992 of 19993',()=>assert.equal(saved.analysis.overall.repairedValid,19992));
test('saved miss is large-pz tolerance corner case',()=>{const m=saved.analysis.missedFaultExamples[0];assert.equal(m.event,147609488);assert.ok(m.originalPz1GeV>3000);assert.ok(m.alarmThresholdGeV>Math.abs(m.residualPz1GeV))});
test('saved invalid output preserves same missed event',()=>assert.equal(saved.analysis.invalidRepairedExamples[0].event,147609488));
test('saved 3 clean metrics untouched',()=>assert.equal(saved.analysis.scenarios.clean.recoveredVsClean.maeGeV,0));
test('saved reproducible source workflow link',()=>assert.ok(saved.verifiedWorkflowUrl.endsWith('/39540715071')));
console.log(JSON.stringify({result:'PASS',passed:Object.keys(checks).length,failed:0,fixture:{rows:events.length,heldout:evaluate(events).heldout},checks},null,2));
