import assert from 'node:assert/strict';
import {generateKeyPairSync} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';import {join} from 'node:path';
import {performance} from 'node:perf_hooks';
import {KET,signPolicy,signIntent,signRequest} from './ket.mjs';
const t=performance.now(),dir=await mkdtemp(join(tmpdir(),'ket-run-'));
const w=generateKeyPairSync('ed25519'),a=generateKeyPairSync('ed25519'),o=generateKeyPairSync('ed25519'),c=generateKeyPairSync('ed25519');
const keys={deployment:'ket',witnessPrivate:w.privateKey,witnessPublic:w.publicKey,adminPublic:a.publicKey,ownerPublic:o.publicKey,clients:{controller:c.publicKey}};
let k,checks=0;const ck=(test,msg)=>{assert.ok(test,msg);checks++};
try{
 k=new KET(join(dir,'kernel.db'),keys);
 ck(k.genesis('a'.repeat(64)).ok,'genesis');
 ck(k.policy(signPolicy(a.privateKey,{deployment:'ket',sequence:0,epoch:0,keys:['controller']})).ok,'policy');
 const initial=k.time();ck(initial.K===0&&initial.T.present.epoch===0,'one kernel present zero');
 ck(initial.T.past.verified===false&&initial.T.future===null,'no fabricated past/future');
 const intent=signIntent(o.privateKey,{deployment:'ket',epoch:1,prior:'a'.repeat(64),next:'b'.repeat(64),nonce:'1'.repeat(32)});
 ck(k.time({future:intent}).T.future.status==='candidate-uncommitted','future uncommitted');
 const req=signRequest(c.privateKey,{deployment:'ket',keyId:'controller',policyEpoch:0,nonce:'2'.repeat(32),action:'CAS',intent});
 const wrapped=k.i(req);ck(wrapped.operator==='i','intent operator');
 const result=k.u(wrapped);ck(result.ok&&result.E==='emerged','understanding executes consequence');
 ck(result.T.present.epoch===1&&result.T.present.hash==='b'.repeat(64),'time advanced');
 ck(k.u(wrapped).reason==='replay','replay fails closed');
 ck(k.u({operator:'x',intent:req}).reason==='intent-required','no third operator');
 ck(k.time({future:{deployment:'ket',epoch:9,prior:'b'.repeat(64)}}).reason==='invalid-future-intent','future gap rejected');
 const current=k.time();ck(current.T.present.epoch===1,'one present state');
 k.close();k=new KET(join(dir,'kernel.db'),keys);
 ck(k.time().T.present.epoch===1,'restart persists');
 console.log(JSON.stringify({status:'PASS',assertions:checks,elapsedMs:+(performance.now()-t).toFixed(3),kernel:1,operators:['i','u'],scopes:['K','E','T'],independentHostVerified:false}));
}finally{k?.close();await rm(dir,{recursive:true,force:true});}