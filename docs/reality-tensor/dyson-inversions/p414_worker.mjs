import {readFile,open} from 'node:fs/promises';
import {createPublicKey,createHash} from 'node:crypto';
import {join} from 'node:path';
import {validateGrant,GenesisAuthority} from './p410_genesis.mjs';
const cfg=JSON.parse(await readFile(process.argv[2],'utf8'));
const sha=x=>createHash('sha256').update(x).digest('hex');
const checkpoint=async stage=>{await new Promise(resolve=>process.send?.({stage},resolve));if(stage===cfg.stopAt)await new Promise(()=>{});};
const key=createPublicKey(cfg.publicKey);
if(!validateGrant(cfg.grant,key,cfg.deployment))throw Error('invalid grant');
const flag=await readFile(join(cfg.registry,'PROVISIONED'),'utf8');
if(flag!=='ROOT0:P412:ACTIVE\n')throw Error('invalid registry');
await checkpoint('before-create');
const target=join(cfg.registry,sha('ROOT0/P412/deployment/'+cfg.deployment)+'.json');
const file=await open(target,'wx',0o600);
await checkpoint('after-create');
const record={deployment:cfg.deployment,grantHash:sha(cfg.grant.signature),stage:'reserved'};
await file.writeFile(JSON.stringify(record)+'\n');
await checkpoint('after-write');
await file.sync();
await checkpoint('after-file-sync');
const folder=await open(cfg.registry,'r');
await folder.sync();await folder.close();
await checkpoint('after-dir-sync');
const authority=GenesisAuthority.provision(cfg.authority,key,cfg.deployment,cfg.grant);
authority.close();
await checkpoint('after-authority-commit');
await file.close();
await checkpoint('done');
setInterval(()=>{},1000);