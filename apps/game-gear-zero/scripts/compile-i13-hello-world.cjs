#!/usr/bin/env node
/* GG-ZERO — compile the existing I-13 Hello World hand-assembled Z80 cartridge.
   Requires Node.js >= 18. No external assembler, emulator or packages.
   This is a reproducible build of the bounded I-13 translation, not a
   general-purpose compiler for the canonical I13-H1.1 language. */
'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const source=path.join(root,'games','i13-hello-world.js');
const destination=path.resolve(root,process.argv[2]||'dist/i13-hello-world-rgb.gg');
const context=vm.createContext({window:{},Uint8Array,Uint8ClampedArray,Float32Array,Math});
vm.runInContext(fs.readFileSync(source,'utf8'),context,{filename:source,timeout:2000});
const rom=context.window.GGHelloWorld.create();
if(!(rom instanceof Uint8Array)||rom.length!==16384)throw Error('Expected exactly 16 KiB of Game Gear ROM');
if(rom[0]!==0xC3||rom[1]!==0x00||rom[2]!==0x01)throw Error('Z80 reset vector does not enter boot at 0100h');
const wordCount=rom.hello?.sourceWords?.length;
if(wordCount!==13||rom.hello?.colors?.length!==16)throw Error('I-13 / RGB dot source metadata mismatch');
fs.mkdirSync(path.dirname(destination),{recursive:true});
fs.writeFileSync(destination,rom);
const check=fs.readFileSync(destination);
if(!check.equals(Buffer.from(rom)))throw Error('Compiled ROM differs from generated bytes');
const sha256=crypto.createHash('sha256').update(check).digest('hex');
console.log(JSON.stringify({result:'COMPILED',rom:path.relative(root,destination),bytes:check.length,sha256,engine:'GG-ZERO original Z80',source:'games/i13-hello-world.js',meaning:'bounded I-13 RGB-dot hand translation'},null,2));
