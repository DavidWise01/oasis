/* FIRST LIGHT: executable Z80 Game Gear cartridge regression tests.
Run: node tests/first-light.test.js */
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context={window:{},Uint8Array,Uint8ClampedArray,Float32Array,Math};
vm.createContext(context);
for(const p of ['core/z80.js','core/gg.js','games/first-light.js']){
 vm.runInContext(fs.readFileSync(path.join(__dirname,'..',p),'utf8'),context,{filename:p});
}
const {GGZ80,GGMachine,GGFirstLight}=context.window;
const report=(function(GGZ80,GGMachine,GGFirstLight){
const checks=[], ok=(name,f)=>{f();checks.push(name)};
const assert=(v,msg)=>{if(!v)throw Error(msg)};
const step=(m,n)=>{for(let i=0;i<n;i++)m.runFrame()};
const boot=()=>{const m=new GGMachine();m.load(GGFirstLight.create());step(m,4);return m};
const rom=GGFirstLight.create();
ok('01 16KiB assembled cartridge',()=>assert(rom.length===16384,'size'));
ok('02 Z80 boot entry at 0x100',()=>assert(rom[0]===0xc3&&rom[1]===0&&rom[2]===1,'reset vector'));
ok('03 executable Z80 interrupt handler',()=>assert(rom[0x38]===0xf5&&rom[0x38+9]===0xed&&rom[0x38+10]===0x4d,'RETI'));
let m=boot();
ok('04 CPU reaches 0xA5 success RAM',()=>assert(m.ram[0]===0xa5,'boot'));
ok('05 Z80 activates VDP graphics and IRQ',()=>assert(m.vdpRegs[1]===0x60,'VDP'));
ok('06 Z80 populates real VRAM name table',()=>assert(m.vram[0x3800]===1&&m.stats.vramWrites>=1500,'VRAM'));
ok('07 64 CRAM writes delivered',()=>assert(m.stats.cramWrites===64&&m.cram[2]===15,'CRAM'));
ok('08 framebuffer is Game Gear LCD size',()=>assert(m.framebuffer.length===92160,'LCD'));
ok('09 rendered pixel colors are nonconstant',()=>{const color=new Set();for(let i=0;i<m.framebuffer.length;i+=4)color.add(m.framebuffer[i]+','+m.framebuffer[i+1]+','+m.framebuffer[i+2]);assert(color.size>=3,'colors '+color.size);});
ok('10 emulated VBlank ISR increments RAM',()=>assert(m.stats.irqRequests>=3&&m.ram[10]>=3,'irq'));
ok('11 sprite boot coordinates are generated by Z80',()=>assert(m.vram[0x3f80]===64&&m.vram[0x3f00]===39,'sprite'));
ok('12 RIGHT key moves sprite and stored position',()=>{m.press('right',true);step(m,10);m.press('right',false);assert(m.ram[1]===9&&m.vram[0x3f80]===72,'x='+m.ram[1]);});
ok('13 maze wall rejects movement on real Z80',()=>{const z=boot();z.press('right',true);step(z,80);z.press('right',false);assert(z.ram[1]===12&&z.ram[4]>=3&&z.vram[0x3f80]===96,'wall x='+z.ram[1]+', hits='+z.ram[4]);});
ok('14 LEFT and UP move and update VDP sprite Y',()=>{const z=boot();z.press('left',true);step(z,10);z.press('left',false);z.press('up',true);step(z,10);z.press('up',false);assert(z.ram[1]<8&&z.ram[2]<5&&z.vram[0x3f00]===z.ram[2]*8-1,'left/up');});
ok('15 ability 1 changes color and PSG tone',()=>{m.press('b1',true);step(m,10);m.press('b1',false);assert(m.ram[9]===1&&m.cram[2]===240&&m.psg.vol[0]===0,'ability1');});
ok('16 audio samples are generated by PSG',()=>assert(m.audioSamples(128).some(x=>Math.abs(x)>.005),'no samples'));
ok('17 ability 2 changes color and tone',()=>{m.press('b2',true);step(m,10);m.press('b2',false);assert(m.ram[9]===2&&m.cram[2]===15&&m.psg.vol[0]===0,'ability2');});
ok('18 releasing key silences PSG and bus counters advance',()=>{step(m,10);assert(m.psg.vol[0]===15&&m.stats.psgWrites>5&&m.stats.portReads>4,'PSG / bus');});
return {count:checks.length,names:checks};

})(GGZ80,GGMachine,GGFirstLight);
report.names.forEach(name=>console.log('PASS '+name));
console.log(report.count+'/'+report.count+' tests passed');
