/* RGB DIFFUSION ARENA - executable Z80 cartridge regression suite
 * Usage: node tests/rgb-diffusion.test.js (Node >=18; zero packages)
 * Classical four-neighbor bitmask propagation, not physical diffusion. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const window={};const sandbox=vm.createContext({window,Uint8Array,Uint8ClampedArray,Float32Array,Math});
for(const file of ['core/z80.js','core/gg.js','games/rgb-diffusion-game.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'..',file),'utf8'),sandbox,{filename:file});
const report=(function(GGMachine,GGRGBDiffusion){const cases=[], assert=(name,p)=>{if(!p)throw Error("FAIL "+name);cases.push(name)}, spawn=()=>{const m=new GGMachine();m.load(GGRGBDiffusion.create());return m},run=(m,n)=>{for(let i=0;i<n;i++)m.runFrame()},key=(m,k,n=6)=>{m.press(k,true);run(m,n);m.press(k,false);run(m,2)};
const cart=GGRGBDiffusion.create(),meta=cart.rgbGame,m=spawn();
assert("01 genuine 16 KiB Game Gear cartridge",cart.length===16384);
assert("02 original CPU reset vector",cart[0]===0xc3&&cart[1]===0&&cart[2]===1);
assert("03 three 1-bit RGB channels",meta.channels.red===1&&meta.channels.green===2&&meta.channels.blue===4);
assert("04 16x12 active 18-stride board",meta.board.join()=== '16,12'&&meta.stride===18);
run(m,8);
assert("05 CPU boot success",m.ram[0x107]===165);
assert("06 actual VDP display enabled",m.vdpRegs[1]===0x60);
assert("07 three seeded RGB emission pulses",m.ram[0x200+38]===1&&m.ram[0x200+51]===2&&m.ram[0x200+206]===4);
assert("08 seed is not a player action",m.ram[0x10f]===0);
assert("09 emulated VRAM writes performed",m.stats.vramWrites>2800);
assert("10 actual rendered LCD 160 x 144",m.framebuffer.length===92160);
assert("11 real sprite placed on board",m.vram[0x3f80]===120&&m.vram[0x3f00]===87);
const before=m.ram[0x200+38+1];run(m,6);
assert("12 Z80 OR diffusion spreads red to neighbor",before===0&&m.ram[0x200+38+1]===1);
const hist=()=>{let bins=new Array(8).fill(0);for(let y=1;y<=12;y++)for(let x=1;x<=16;x++)bins[m.ram[0x200+y*18+x]]++;return bins};
run(m,30);
const bins=hist();
assert("13 expanding wave has dozens of active cells",bins.slice(1).reduce((a,b)=>a+b,0)>20);
assert("14 no automatic score from seeded diffusion",m.ram[0x106]===0);
assert("15 CPU executes VBlank ISR",m.ram[0x108]>=40);
const x0=m.ram[0x100];key(m,"right",12);
assert("16 physical Game Gear RIGHT moves player",m.ram[0x100]>x0&&m.vram[0x3f80]>120);
key(m,"left",12);
assert("17 LEFT reverses movement",m.ram[0x100]===x0);
const initial=m.ram[0x102];key(m,"b2",3);
assert("18 button 2 switches R to G",initial===1&&m.ram[0x102]===2);
key(m,"b2",3);
assert("19 separate button 2 press switches G to B",m.ram[0x102]===4);
key(m,"b2",3);
assert("20 third button 2 press returns to R",m.ram[0x102]===1);
key(m,"b1",6);
assert("21 button 1 writes actual paint and receipt",m.ram[0x10f]===1);
assert("22 paint ORs RGB bit into field",m.ram[0x200+6*18+8]&1);
run(m,100);
assert("23 reactor reaches white and awards point",m.ram[0x200+116]===7&&m.ram[0x106]===1&&m.ram[0x109]===1);
const score=m.ram[0x106];run(m,15);
assert("24 reactor completion is one-time receipt",m.ram[0x106]===score);
key(m,"start",3);
assert("25 START restarts seeded round but keeps score",m.ram[0x109]===0&&m.ram[0x10f]===0&&m.ram[0x106]===score&&m.ram[0x200+38]===1&&m.ram[0x10e]<=2);
assert("26 VRAM continues rendering after reset",m.stats.vramWrites>3200);
const attract=spawn();run(attract,150);
assert("27 attract mode loops the RGB wave and avoids phantom score",attract.ram[0x10f]===0&&attract.ram[0x106]===0&&attract.ram[0x10e]<10);
return {count:cases.length,cases,frame:m.frames,final:{score:m.ram[0x106],rect:m.ram[0x200+116],ink:m.ram[0x102]},hist:bins,bytes:cart.length};
})(window.GGMachine,window.GGRGBDiffusion);
report.cases.forEach(x=>console.log('PASS',x));
console.log(report.count+'/'+report.count+' pass');
