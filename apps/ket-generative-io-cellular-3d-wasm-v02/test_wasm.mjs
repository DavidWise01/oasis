// Compact Node assertions: actual embedded WASM and frozen KET controller.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const bytes=fs.readFileSync(new URL('./ket_cellular.wasm',import.meta.url));
const mod=await WebAssembly.instantiate(bytes,{});
const e=mod.instance.exports;
let checks=0;
const ck=(value,message)=>{assert.ok(value,message);checks++;};
ck(WebAssembly.validate(bytes),'real wasm32');
ck(WebAssembly.Module.imports(mod.module).length===0,'no runtime imports');
ck(e.configure(2.4,.88,.14,3,42,2,45,1,.1)===1080,'3 layers x 360 ports');
ck(e.cell_count()===1080,'cell count');
ck(e.get_layers()===3,'radial layers');
ck(e.xyz_ptr()>0 && e.cells_ptr()>0 && e.ages_ptr()>0,'memory pointers');
const xyz=new Float32Array(e.memory.buffer,e.xyz_ptr(),1080*3);
ck(xyz.every(Number.isFinite),'genuine finite 3D points');
const cells=new Int8Array(e.memory.buffer,e.cells_ptr(),1080);
ck([...cells].every(s=>s>=-1&&s<=1),'ternary states');
ck(e.get_active()>0,'initial live field');
const hash0=e.get_checksum()>>>0;
for(let i=0;i<6;i++)e.advance();
ck(Math.abs(e.get_phase()-5.7)<1e-9,'first six phase lag');
for(let i=6;i<12;i++)e.advance();
ck(Math.abs(e.get_phase()-12)<1e-9,'paired phase recovered');
for(let i=12;i<360;i++)e.advance();
ck(e.get_generation()===360,'360 generations');
ck(Math.abs(e.get_phase()-360)<1e-9,'360 degree closure');
ck(Math.abs(e.get_speed()-1)<1e-9,'original speed');
ck(e.get_active()>0,'living cells at gen 360');
const hash1=e.get_checksum()>>>0;
ck(hash0!==hash1,'cell field evolved');
e.configure(2.4,.88,.14,3,42,2,45,1,.1);
ck((e.get_checksum()>>>0)===hash0,'deterministic seeded reset');
for(let i=0;i<360;i++)e.advance();
ck((e.get_checksum()>>>0)===hash1,'deterministic 360-run replay');
ck(e.configure(2.4,.88,.14,6,42,2,45,1,.1)===2160,'six layers maximum');
ck(e.configure(2.4,.88,.14,1,42,2,45,1,.1)===360,'one layer minimum');
ck(e.configure(2.4,.88,.14,7,42,2,45,1,.1)===0,'bad layer count rejected');
ck(e.configure(.5,.88,.14,3,42,2,45,1,.1)===0,'invalid major radius rejected');
ck(e.configure(2.4,.88,.14,3,42,2,45,1,.1)===1080,'restore default');
const sha=createHash('sha256').update(bytes).digest('hex');
console.log(JSON.stringify({checks,wasm_sha256:sha,default_cells:e.cell_count(),full_cycle_phase:360,seeded_replay_passed:true},null,2));
