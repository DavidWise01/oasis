import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const bin=fs.readFileSync(new URL('./vector_toroid.wasm',import.meta.url));
let checks=0;const ck=(name,fn)=>{fn();checks++;};
const init=async()=>{let r=await WebAssembly.instantiate(bin,{});return r.instance.exports;};
const ex=await init();
ck('valid module',()=>assert.equal(WebAssembly.validate(bin),true));
ck('no imports',()=>assert.equal(WebAssembly.Module.imports(new WebAssembly.Module(bin)).length,0));
ck('actual wasm binary',()=>assert.equal(Buffer.from(bin.subarray(0,4)).toString('hex'),'0061736d'));
ck('invalid intersecting radius',()=>assert.equal(ex.configure(.3,.8,3,.5,0,0,0,42,0),0));
ck('invalid negative gap',()=>assert.equal(ex.configure(2,.6,3,-1,0,0,0,42,0),0));
ck('invalid address',()=>assert.equal(ex.configure(2,.6,3,.8,360,0,0,42,0),0));
ck('invalid mode',()=>assert.equal(ex.configure(2,.6,3,.8,0,0,4,42,0),0));
ck('valid twin initialization',()=>assert.equal(ex.configure(1.9,.65,3,.8,0,199,0,42,0),2160));
ck('per torus 1080 derived cells',()=>assert.equal(ex.one_count(),1080));
ck('port index 0',()=>assert.equal(ex.get_port(0),0));
ck('arbitrary second port 199',()=>assert.equal(ex.get_port(1),199));
ck('gate off by default',()=>assert.equal(ex.get_gate(),0));
ck('position float array exists',()=>assert.ok(ex.positions_ptr()>=0));
ck('no external box in geometry',()=>assert.equal(fs.readFileSync(new URL('./src/vector_toroid.c',import.meta.url),'utf8').includes('box_mesh'),false));
// For each directional test, no initial background excitation; manual inject on one torus
ex.configure(1.9,.65,3,.8,0,199,0,42,0);ex.stimulate(0,0);ex.advance();
ck('no TX when OFF',()=>assert.equal(ex.get_tx(0)+ex.get_tx(1),0));
const b199=1*1080+199*3+2;
const stateOff=new Int8Array(ex.memory.buffer)[ex.cells_ptr()+b199];
ex.configure(1.9,.65,3,.8,0,199,1,42,0);ex.stimulate(0,0);ex.advance();
ck('A->B exactly one TX',()=>assert.equal(ex.get_tx(0),1));
ck('A->B not reverse',()=>assert.equal(ex.get_tx(1),0));
ck('B excited by A',()=>assert.equal(new Int8Array(ex.memory.buffer)[ex.cells_ptr()+b199],1));
ck('A->B changes receiver against OFF',()=>assert.notEqual(stateOff,1));
ex.configure(1.9,.65,3,.8,0,199,2,42,0);ex.stimulate(1,199);ex.advance();
ck('B->A exactly one TX',()=>assert.equal(ex.get_tx(1),1));
ck('B->A not reverse',()=>assert.equal(ex.get_tx(0),0));
ck('A excited by B',()=>assert.equal(new Int8Array(ex.memory.buffer)[ex.cells_ptr()+2],1));
ex.configure(1.9,.65,3,.8,0,199,3,42,0);ex.stimulate(0,0);ex.stimulate(1,199);ex.advance();
ck('BOTH A->B TX',()=>assert.equal(ex.get_tx(0),1));
ck('BOTH B->A TX',()=>assert.equal(ex.get_tx(1),1));
ck('gate cannot be invalid',()=>assert.equal(ex.set_gate(7),0));
ck('gate toggles OFF',()=>assert.equal(ex.set_gate(0),1));
ck('ports can be anywhere on surface',()=>assert.equal(ex.set_ports(359,0),1));
ck('new arbitrary port A',()=>assert.equal(ex.get_port(0),359));
ck('new arbitrary port B',()=>assert.equal(ex.get_port(1),0));
ck('set gap zero allowed',()=>assert.equal(ex.set_gap(0),1));
ck('set gap larger allowed',()=>assert.equal(ex.set_gap(2.5),1));
ck('get gap',()=>assert.equal(ex.get_gap(),2.5));
ck('default vector point A',()=>{ex.configure(1.9,.65,3,4.2,0,199,0,42,0);assert.deepEqual([0,1,2].map(i=>ex.get_vector(0,i)),[-1,0,0]);});
ck('default vector point B',()=>assert.deepEqual([0,1,2].map(i=>ex.get_vector(1,i)),[1,0,0]));
ck('rejected vector <-1',()=>assert.equal(ex.set_vectors(-2,0,0,0,0,0),0));
ck('rejected vector >+1',()=>assert.equal(ex.set_vectors(0,0,0,0,2,0),0));
ck('A arbitrary vector',()=>{assert.equal(ex.set_vectors(0,1,-1,-1,0,1),1);assert.deepEqual([0,1,2].map(i=>ex.get_vector(0,i)),[0,1,-1]);});
ck('B arbitrary vector',()=>assert.deepEqual([0,1,2].map(i=>ex.get_vector(1,i)),[-1,0,1]));
ck('center separation squared',()=>assert.ok(Math.abs(ex.center_distance_squared()-6*4.2*4.2)<1e-8));
ck('coincident center allowed',()=>{assert.equal(ex.set_vectors(0,0,0,0,0,0),1);assert.equal(ex.center_distance_squared(),0);});
ck('two tori remain separately allocated',()=>assert.equal(ex.cell_count(),2160));
ck('27 coordinate options on A',()=>{for(let x=-1;x<=1;x++)for(let y=-1;y<=1;y++)for(let z=-1;z<=1;z++)assert.equal(ex.set_vectors(x,y,z,0,0,0),1);});
ck('27 coordinate options on B',()=>{for(let x=-1;x<=1;x++)for(let y=-1;y<=1;y++)for(let z=-1;z<=1;z++)assert.equal(ex.set_vectors(0,0,0,x,y,z),1);});
const beforeA=ex.get_phase(0),beforeB=ex.get_phase(1);
ck('phase both finite',()=>{assert.ok(Number.isFinite(beforeA));assert.ok(Number.isFinite(beforeB));});
ex.configure(1.9,.65,3,.8,0,199,0,42,40);
for(let i=0;i<360;i++)ex.advance();
ck('360 ticks',()=>assert.equal(ex.get_tick(),360));
ck('phase A closes',()=>assert.ok(Math.abs(ex.get_phase(0)-360)<1e-8));
ck('phase B closes',()=>assert.ok(Math.abs(ex.get_phase(1)-360)<1e-8));
ck('speed A restored',()=>assert.ok(Math.abs(ex.get_speed(0)-1)<1e-8));
ck('speed B restored',()=>assert.ok(Math.abs(ex.get_speed(1)-1)<1e-8));
ck('no transfers OFF across 360',()=>assert.equal(ex.get_tx(0)+ex.get_tx(1),0));
const endDigest=ex.get_checksum()>>>0;
ex.configure(1.9,.65,3,.8,0,199,0,42,40);
for(let i=0;i<360;i++)ex.advance();
ck('deterministic checksum replay',()=>assert.equal(ex.get_checksum()>>>0,endDigest));
const stats={schema:'KET/VECTOR_POINTS/3D_WASM/v04',checks,passed:checks,wasm_sha256:crypto.createHash('sha256').update(bin).digest('hex'),twin_cells:ex.cell_count(),per_torus:ex.one_count(),full_cycle_deg:ex.get_phase(0),mode:'OFF',cross_transfers:ex.get_tx(0)+ex.get_tx(1),digest:endDigest};
fs.writeFileSync(new URL('./audit.json',import.meta.url),JSON.stringify(stats,null,2)+'\n');
console.log(JSON.stringify(stats,null,2));
