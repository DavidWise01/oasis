'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
let passed=0;
const check=(name,fn)=>{fn();passed++};
const registry=['n',...'abcdefghijklm',...'opqrstuvwx','y','z',...'12345678','9','>','|',':','"','^','(','-','+','.0x'];
check('44-token address space',()=>assert.equal(registry.length,44));
check('all symbols unique',()=>assert.equal(new Set(registry).size,44));
check('n at zero',()=>assert.equal(registry[0],'n'));
check('HONEY addresses',()=>assert.deepEqual([...'honey'].map(c=>registry.indexOf(c)),[8,14,0,5,24]));
for(let b=0;b<256;b++)check('byte '+b,()=>{const hi=Math.floor(b/44),lo=b%44;assert.ok(hi>=0&&hi<=5&&lo>=0&&lo<44);assert.equal(hi*44+lo,b)});
check('six phases',()=>assert.match(html,/\{name:'REMEMBER',units:0/));
check('balanced return',()=>assert.equal(333367-333367,0));
check('17 midpoint',()=>assert.equal((673367-333367)/2,170000));
check('OSIMODEL bus',()=>assert.match(html,/busSlots:8\*208/));
check('freeze reference',()=>assert.match(html,/astrophage-full-stack-v1\/FREEZE.md/));
check('generation terminal state',()=>assert.match(html,/GENESIS  :: TERMINATED/));
check('disabled status',()=>assert.match(html,/STATUS   :: DISABLED/));
check('explicit failure boundary',()=>assert.match(html,/ON_FAULT :: ISOLATE → RETAIN → REPORT/));
check('Confluence identity',()=>assert.match(html,/\{\{C\}\}onfluence/));
check('Sapphon substrate',()=>assert.match(html,/Ssaphone Substrate/));
check('Ether is symbolic',()=>assert.match(html,/conceptual information environment/));
check('quanta event unit',()=>assert.match(html,/one symbolic event/));
check('four drill modes',()=>['valid','token','witness','mismatch'].forEach(x=>assert.match(html,new RegExp('value="'+x+'"'))));
check('failure quarantine branch',()=>assert.match(html,/QUARANTINE \/ NO PROPAGATION/));
check('local reset route',()=>assert.match(html,/fault-clear/));
check('drill cannot restart genesis',()=>assert.match(html,/RESTART  :: NOT AUTHORIZED IN THIS PAGE/));
check('no externally hosted scripts',()=>assert.doesNotMatch(html,/<script\s+src=/));
check('no externally hosted CSS',()=>assert.doesNotMatch(html,/<link[^>]+rel="stylesheet"/));
check('preserved interactive cycle',()=>assert.match(html,/id="cycle-next"/));
check('preserved interactive codec',()=>assert.match(html,/id="encoder-input"/));
check('drill result surface',()=>assert.match(html,/id="fault-status"/));
console.log(`PASS ${passed}/${passed} Confluence page checks`);