'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
let passed=0;
const check=(name,fn)=>{fn();passed++;};
const r=['n',...'abcdefghijklm',...'opqrstuvwx','y','z',...'12345678','9','>','|',':','"','^','(','-','+','.0x'];
check('size',()=>assert.equal(r.length,44));
check('unique',()=>assert.equal(new Set(r).size,44));
check('anchors',()=>assert.deepEqual([r[0],r[43]],['n','.0x']));
check('HONEY',()=>assert.deepEqual([...'honey'].map(x=>r.indexOf(x)),[8,14,0,5,24]));
for(let byte=0;byte<256;byte++)check('byte '+byte,()=>{const hi=Math.floor(byte/44),lo=byte%44;assert.ok(hi>=0&&hi<=5&&lo>=0&&lo<44);assert.equal(hi*44+lo,byte)});
check('balance',()=>assert.equal(333367-333367,0));
check('midpoint 17',()=>assert.equal((673367-333367)/2,170000));
check('shared LIVE',()=>assert.match(html,/phase===5\)\{phase=1;cycles\+\+;/));
check('eight-lane bus',()=>assert.match(html,/busSlots:8\*208/));
check('freeze link',()=>assert.match(html,/astrophage-full-stack-v1\/FREEZE.md/));
check('adapter source link',()=>assert.match(html,/adapter.mjs/));
check('self-contained',()=>{assert.doesNotMatch(html,/<script\s+src=/);assert.doesNotMatch(html,/<link[^>]+rel="stylesheet"/)});
console.log('PASS '+passed+'/'+passed+' checks');
